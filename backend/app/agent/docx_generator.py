"""Deterministic DOCX rendering for validated document content."""

import re
import secrets
from datetime import date
from pathlib import Path

from docx import Document
from docx.shared import Inches, Pt
from pydantic import BaseModel, ConfigDict, Field

from backend.app.agent.document_content import DocumentContent
from backend.app.agent.docx_templates import TemplateNotFoundError, render_document
from backend.app.agent.models import DocumentPlan
from backend.app.agent.placeholders import (
    PlaceholderVerificationError,
    RenderedPlaceholder,
    collect_rendered_placeholders,
)

PROJECT_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_OUTPUT_DIR = PROJECT_ROOT / "var" / "output"
MAX_SLUG_LENGTH = 48
_IDENTIFIER_BYTES = 6
_COMMAND_PREFIXES = {
    "a",
    "an",
    "create",
    "draft",
    "generate",
    "make",
    "prepare",
    "produce",
    "the",
    "write",
}


class DocxGenerationError(RuntimeError):
    """Raised when a DOCX document cannot be generated or verified."""


class GeneratedDocument(BaseModel):
    """Verified DOCX output and its effective metadata and placeholders."""

    model_config = ConfigDict(extra="forbid")

    filename: str = Field(min_length=1)
    document_date: str = Field(min_length=1)
    document_version: str = Field(min_length=1)
    placeholders: list[RenderedPlaceholder] = Field(default_factory=list)


def _slugify(request: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", request.lower()).strip("-")
    parts = [part for part in slug.split("-") if part]
    while parts and parts[0] in _COMMAND_PREFIXES:
        parts.pop(0)
    slug = "-".join(parts)[:MAX_SLUG_LENGTH].strip("-")
    return slug or "document"


def _new_filename(request: str) -> str:
    slug = _slugify(request)
    identifier = secrets.token_hex(_IDENTIFIER_BYTES)
    return f"{slug}-{identifier}.docx"


def _configure_styles(document: Document) -> None:
    for section in document.sections:
        section.top_margin = Inches(1)
        section.bottom_margin = Inches(1)
        section.left_margin = Inches(1)
        section.right_margin = Inches(1)

    normal = document.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(11)
    normal.paragraph_format.space_after = Pt(6)
    normal.paragraph_format.line_spacing = 1.15

    title = document.styles["Title"]
    title.font.name = "Calibri"
    title.font.size = Pt(24)
    title.font.bold = True

    heading = document.styles["Heading 1"]
    heading.font.name = "Calibri"
    heading.font.size = Pt(14)
    heading.font.bold = True
    heading.paragraph_format.space_before = Pt(12)
    heading.paragraph_format.space_after = Pt(6)


def _populate_document(
    document: Document,
    content: DocumentContent,
    document_date: str,
    document_version: str,
) -> None:
    render_document(document, content, document_date, document_version)


def _apply_metadata(document: Document, content: DocumentContent) -> None:
    properties = document.core_properties
    properties.title = content.title
    properties.author = "FluidAI Doc Builder"
    properties.last_modified_by = "FluidAI Doc Builder"
    properties.subject = content.title
    properties.category = content.document_type.value
    properties.comments = "Generated by FluidAI Doc Builder"


def _remove_partial(path: Path) -> None:
    try:
        path.unlink(missing_ok=True)
    except OSError:
        pass


def _verify_document(destination: Path, content: DocumentContent) -> Document:
    try:
        generated = Document(destination)
    except Exception as exc:
        raise DocxGenerationError(
            "The generated document could not be reopened."
        ) from exc

    if not generated.paragraphs:
        raise DocxGenerationError("The generated document has no content.")

    if generated.paragraphs[0].text.strip() != content.title:
        raise DocxGenerationError("The generated document title could not be verified.")

    headings = [
        paragraph.text.strip()
        for paragraph in generated.paragraphs
        if paragraph.style.name == "Heading 1"
    ]
    expected = [section.heading.strip() for section in content.sections]
    actual_index = 0
    for expected_heading in expected:
        while (
            actual_index < len(headings) and headings[actual_index] != expected_heading
        ):
            actual_index += 1
        if actual_index == len(headings):
            raise DocxGenerationError(
                "The generated document sections could not be verified."
            )
        actual_index += 1

    return generated


class DocxGenerator:
    """Render validated content to a safely named DOCX file."""

    def __init__(self, output_dir: Path | str = DEFAULT_OUTPUT_DIR):
        self._output_dir = Path(output_dir)

    def generate(
        self,
        content: DocumentContent,
        request: str,
        plan: DocumentPlan | None = None,
        today: date | None = None,
    ) -> GeneratedDocument:
        output_dir = self._output_dir.expanduser().resolve()
        try:
            output_dir.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            raise DocxGenerationError(
                "The document output directory could not be prepared."
            ) from exc

        filename = self._allocate_filename(output_dir, request)
        destination = (output_dir / filename).resolve()
        if not destination.is_relative_to(output_dir):
            raise DocxGenerationError(
                "The generated document path is outside the output directory."
            )

        document_date = (
            plan.document_date if plan and plan.document_date else None
        ) or (today or date.today()).isoformat()
        document_version = (
            plan.document_version if plan and plan.document_version else "1.0"
        )

        try:
            document = Document()
            _configure_styles(document)
            _populate_document(
                document,
                content,
                document_date,
                document_version,
            )
            _apply_metadata(document, content)
            document.save(destination)
            verified = _verify_document(destination, content)
            placeholders = collect_rendered_placeholders(verified, plan)
        except TemplateNotFoundError as exc:
            _remove_partial(destination)
            raise DocxGenerationError("Unsupported document type.") from exc
        except PlaceholderVerificationError as exc:
            _remove_partial(destination)
            raise DocxGenerationError(
                "The generated document contains an unexplained placeholder."
            ) from exc
        except DocxGenerationError:
            _remove_partial(destination)
            raise
        except OSError as exc:
            _remove_partial(destination)
            raise DocxGenerationError("The document could not be saved.") from exc
        except Exception as exc:
            _remove_partial(destination)
            raise DocxGenerationError("The document could not be generated.") from exc

        return GeneratedDocument(
            filename=filename,
            document_date=document_date,
            document_version=document_version,
            placeholders=placeholders,
        )

    def _allocate_filename(self, output_dir: Path, request: str) -> str:
        for _ in range(10):
            filename = _new_filename(request)
            if not (output_dir / filename).exists():
                return filename
        raise DocxGenerationError("A unique document filename could not be allocated.")
